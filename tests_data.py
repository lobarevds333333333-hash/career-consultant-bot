def _join_names(labels: list[str]) -> str:
    if not labels:
        return ""
    if len(labels) == 1:
        return labels[0]
    if len(labels) == 2:
        return f"{labels[0]} и {labels[1]}"
    return ", ".join(labels[:-1]) + f" и {labels[-1]}"


def _ranked(scores: dict[str, int]) -> list[tuple[str, int]]:
    """Типы, отсортированные по убыванию баллов (при равенстве — порядок словаря)."""
    return sorted(scores.items(), key=lambda item: -item[1])


def _merge_professions(dominant: list[str], types: dict, per_type: int = 4) -> str:
    """Собирает список профессий из доминирующих типов без повторов."""
    result: list[str] = []
    for key in dominant:
        result.extend(types[key]["professions"][:per_type])
    unique = list(dict.fromkeys(result))
    return ", ".join(unique[: per_type * len(dominant)])


def _dominant_names(test_key: str, payload: dict) -> str:
    """Красивый список ведущих типов: '🎨 <b>Артист</b> и 📋 <b>Организатор</b>'."""
    types = _TYPE_MAPS[test_key]
    labels = [
        f"{types[key]['emoji']} <b>{types[key]['name']}</b>"
        for key in payload.get("dominant", [])
    ]
    return _join_names(labels)


def _dominant_with_scores(test_key: str, payload: dict) -> str:
    """Компактный список для менеджера: '💰 Деньги (4 из 10), 🕊 Свобода (3 из 10)'."""
    types = _TYPE_MAPS[test_key]
    scores = payload.get("scores", {})
    parts = []
    for key in payload.get("dominant", []):
        score = scores.get(key, 0)
        suffix = "" if test_key == "career" else " из 10"
        parts.append(f"{types[key]['emoji']} {types[key]['name']} ({score}{suffix})")
    return ", ".join(parts)


def _breakdown(test_key: str, scores: dict[str, int]) -> str:
    """Баллы по всем типам — отдельными строками."""
    types = _TYPE_MAPS[test_key]
    return "\n".join(
        f"{t['emoji']} {t['name']} — {scores[key]}"
        for key, t in types.items()
    )


