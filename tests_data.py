def build_career_result(answers: list[str]) -> tuple[str, dict]:
    """Результат теста на профориентацию: текст + данные для БД."""
    scores = {key: 0 for key in CAREER_TYPES}
    option_points = {key: points for key, _label, points in CAREER_OPTIONS}
    for question, answer in zip(CAREER_QUESTIONS, answers):
        scores[question["type"]] += option_points.get(answer, 0)

    payload: dict = {"scores": scores, "dominant": []}
    ranked = _ranked(scores)
    max_score = ranked[0][1]

    header = "📊 <b>Результат теста на профориентацию</b>\n\n"
    if max_score == 0:
        return header + (
            "🤔 По вашим ответам не получилось выделить явные предпочтения — "
            "большинство занятий вы оценили нейтрально.\n\n"
            "Попробуйте пройти тест ещё раз, отвечая более смело, "
            "или обсудите свои сомнения на консультации."
        ), payload

    leaders = [key for key, score in ranked if score == max_score]
    if len(leaders) > 2:
        dominant = leaders[:3]
    else:
        dominant = list(leaders)
        # Добавляем второй тип, если он ненулевой и близок к лидеру
        if (
            len(dominant) == 1
            and len(ranked) > 1
            and ranked[1][1] >= max_score - 1
            and ranked[1][1] >= 1
        ):
            dominant.append(ranked[1][0])
    payload["dominant"] = dominant

    lines = [header + f"Ваши ведущие типы — {_dominant_names('career', payload)}."]
    if len(leaders) > 2:
        lines.append(
            "Несколько типов выражены одинаково сильно — у вас широкая направленность. "
            "Обратите внимание на первые из них:"
        )
    for key in dominant:
        t = CAREER_TYPES[key]
        lines.append(f"\n{t['emoji']} <b>{t['name']}</b> — {scores[key]} из 2\n{t['description']}")

    spheres = "; ".join(CAREER_TYPES[key]["spheres"] for key in dominant)
    lines.append(f"\n💼 <b>Подходящие сферы:</b> {spheres}")
    lines.append(f"🧭 <b>Возможные профессии:</b> {_merge_professions(dominant, CAREER_TYPES)}")
    lines.append("\n📈 <b>Баллы по всем типам:</b>")
    lines.append(_breakdown("career", scores))
    return "\n".join(lines), payload


